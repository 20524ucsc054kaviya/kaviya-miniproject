SELECT STUDENT_ID, STUDENT_NAME, SUBJECT,
       MARKS_OBTAINED, MAX_MARKS, EXAM_DATE
FROM EXAM_RESULTS;
SELECT STUDENT_ID, STUDENT_NAME, SUBJECT,
       MARKS_OBTAINED,
       ROUND((MARKS_OBTAINED / MAX_MARKS) * 100, 2)
       AS PERCENTAGE,
       CASE
           WHEN (MARKS_OBTAINED / MAX_MARKS) * 100 >= 90
               THEN 'A+'
           WHEN (MARKS_OBTAINED / MAX_MARKS) * 100 >= 80
               THEN 'A'
           WHEN (MARKS_OBTAINED / MAX_MARKS) * 100 >= 60
               THEN 'B'
           WHEN (MARKS_OBTAINED / MAX_MARKS) * 100 >= 40
               THEN 'C'
           ELSE 'F'
       END AS GRADE
FROM EXAM_RESULTS;
SELECT SUBJECT,
       ROUND(AVG(MARKS_OBTAINED), 2) AS AVERAGE_MARKS
FROM EXAM_RESULTS
GROUP BY SUBJECT;
SELECT STUDENT_ID, STUDENT_NAME, SUBJECT,
       MARKS_OBTAINED
FROM EXAM_RESULTS
WHERE (MARKS_OBTAINED / MAX_MARKS) * 100 < 40;
SELECT SUBJECT,
       MAX(MARKS_OBTAINED) AS HIGHEST_MARK
FROM EXAM_RESULTS
GROUP BY SUBJECT;
