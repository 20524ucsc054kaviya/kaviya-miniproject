CREATE TABLE EXAM_RESULTS (
    STUDENT_ID NUMBER,
    STUDENT_NAME VARCHAR2(50),
    SUBJECT VARCHAR2(30),
    MARKS_OBTAINED NUMBER,
    MAX_MARKS NUMBER,
    EXAM_DATE DATE,
    CONSTRAINT PK_EXAM PRIMARY KEY
    (STUDENT_ID, SUBJECT),
    CONSTRAINT CHK_MARKS CHECK (
        MARKS_OBTAINED >= 0 AND
        MAX_MARKS > 0 AND
        MARKS_OBTAINED <= MAX_MARKS
    )
);
